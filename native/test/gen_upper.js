// Generates ../src/upper_table.h from node's String.prototype.toUpperCase() (full Unicode
// case mapping, locale independent), so alm_normalize_seed matches the web byte for byte.
//   node native/test/gen_upper.js > native/src/upper_table.h
'use strict';
const simple = [], special = [];
for (let c = 0; c <= 0x10FFFF; c++) {
  if (c >= 0xD800 && c <= 0xDFFF) continue;
  const s = String.fromCodePoint(c), u = s.toUpperCase();
  if (u === s) continue;
  const cps = Array.from(u, ch => ch.codePointAt(0));
  if (cps.length === 1) simple.push([c, cps[0] - c]);
  else special.push([c, cps]);
}
// compress simple mappings into runs: start, count, stride (1 or 2), delta
const runs = [];
for (let i = 0; i < simple.length;) {
  const [c0, d] = simple[i];
  let best = 1, bestStride = 1;
  for (const stride of [1, 2]) {
    let n = 1;
    while (i + n < simple.length && simple[i + n][0] === c0 + n * stride && simple[i + n][1] === d) n++;
    if (n > best) { best = n; bestStride = stride; }
  }
  runs.push([c0, best, bestStride, d]);
  i += best;
}
const hex = v => '0x' + v.toString(16).toUpperCase();
let o = '/* upper_table.h - GENERATED by native/test/gen_upper.js from node ' + process.version +
  ' (ICU ' + process.versions.icu + ', Unicode ' + process.versions.unicode + ').\n' +
  ' * Full, locale-independent upper-case mapping = String.prototype.toUpperCase(). Do not edit. */\n' +
  '#ifndef UPPER_TABLE_H\n#define UPPER_TABLE_H\n#include <stdint.h>\n\n' +
  '/* simple 1:1 mappings: code points start, start+stride, ... (count of them) map to c + delta */\n' +
  'typedef struct { uint32_t start; uint16_t count; uint8_t stride; int32_t delta; } UpRun;\n' +
  'static const UpRun UP_RUNS[] = {\n';
o += runs.map(r => `    {${hex(r[0])}, ${r[1]}, ${r[2]}, ${r[3]}}`).join(',\n') + '\n};\n\n';
o += '/* one-to-many expansions (SpecialCasing.txt, unconditional) */\n' +
  'typedef struct { uint32_t cp; uint16_t up[3]; } UpSpecial;\n' +
  'static const UpSpecial UP_SPECIAL[] = {\n';
for (const [, cps] of special) if (cps.some(v => v > 0xFFFF) || cps.length > 3) throw new Error('table shape');
o += special.map(([c, cps]) => `    {${hex(c)}, {${[0,1,2].map(k => hex(cps[k] || 0)).join(', ')}}}`).join(',\n') + '\n};\n\n#endif\n';
process.stdout.write(o);
process.stderr.write(`runs ${runs.length}, specials ${special.length}\n`);
